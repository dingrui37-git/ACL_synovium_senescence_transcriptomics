    "MDS_input",
    "MDS_top_genes",
    "MDS_gene_selection"
  ),
  value = c(
    fix_version,
    nrow(count_mat),
    nrow(dge_filtered$counts),
    nrow(count_mat) - nrow(dge_filtered$counts),
    ncol(count_mat),
    "edgeR_TMM",
    1,
    "prcomp(t(filtered_TMM_logCPM), center=TRUE, scale.=FALSE)",
    "limma::plotMDS(filtered_TMM_logCPM, top=500, gene.selection='common')",
    "filtered TMM-normalized logCPM matrix",
    500,
    "common"
