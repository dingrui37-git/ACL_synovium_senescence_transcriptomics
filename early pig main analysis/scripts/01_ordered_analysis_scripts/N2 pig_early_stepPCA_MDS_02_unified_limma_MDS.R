  cleaned_files <- character(0)
  for (d in subdirs) {
    if (dir.exists(d)) {
      files <- list.files(d, full.names = TRUE)
      if (length(files) > 0) {
        base <- basename(files)
        idx <- Reduce(`|`, lapply(clean_patterns, function(p) grepl(p, base)))
        targets <- files[idx]
        # Keep the current log connection target until the end, if present.
        targets <- setdiff(normalizePath(targets, winslash = "/", mustWork = FALSE),
                           normalizePath(log_file, winslash = "/", mustWork = FALSE))
        if (length(targets) > 0) {
          ok <- file.remove(targets)
          cleaned_files <- c(cleaned_files, targets[ok])
        }
      }
    }
  }
  cat("Number of previous StepPCA_MDS_02 files removed:", length(cleaned_files), "\n")
