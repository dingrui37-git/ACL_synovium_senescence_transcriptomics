# StepPCA_MDS_02_unified_limma_MDS.R
# English note: This script performs sample-level PCA and MDS for the early pig synovium dataset using the gene-level raw count matrix. Lowly expressed genes are filtered with edgeR::filterByExpr, TMM normalization is performed with edgeR::calcNormFactors, PCA is performed on filtered TMM-normalized logCPM values, and MDS is performed on the same filtered TMM-normalized logCPM matrix using limma::plotMDS for consistency with the mouse discovery dataset. All outputs, source data, figures, logs, method parameters, and reproducibility information are saved to a manuscript-ready supplementary folder.

