# Remove only previous outputs generated by this same step, not the entire S1 folder.
cleanup_step_files <- function(dir_path, prefix) {
  if (!dir.exists(dir_path)) return(invisible(NULL))
  old_files <- list.files(dir_path, pattern = paste0("^", prefix), full.names = TRUE)
  if (length(old_files) > 0) unlink(old_files, recursive = TRUE, force = TRUE)
  invisible(NULL)
}
