          file.path(subdirs["tables"], "StepPCA_MDS_02_PCA_variance_explained.csv"),
          row.names = FALSE)

pca_coord <- data.frame(
  sample_id = rownames(pca_obj$x),
  PC1 = pca_obj$x[, 1],
  PC2 = pca_obj$x[, 2],
  PC3 = if (ncol(pca_obj$x) >= 3) pca_obj$x[, 3] else NA_real_,
  PC4 = if (ncol(pca_obj$x) >= 4) pca_obj$x[, 4] else NA_real_,
  stringsAsFactors = FALSE
)
