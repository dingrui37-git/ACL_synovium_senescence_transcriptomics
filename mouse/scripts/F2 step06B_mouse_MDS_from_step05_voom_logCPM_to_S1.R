# This script generates within-timepoint mouse MDS QC plots for 1W and 4W only.
# Inputs are the saved Step05 paired limma-voom second voom-transformed logCPM matrices.
# Outputs are saved under supplement/S1 for manuscript-ready supplemental QC records.

