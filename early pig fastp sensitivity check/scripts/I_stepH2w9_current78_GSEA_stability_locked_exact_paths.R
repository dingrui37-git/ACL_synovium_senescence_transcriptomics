    diag_df <- data.frame(
      pathway = names(pathways),
      n_genes_in_pathway = vapply(pathways, length, integer(1)),
      n_genes_present_in_rank = pathway_overlap_n,
      stringsAsFactors = FALSE
    )
    write_csv(diag_df, diag_file)
    stop("No Hallmark pathways passed fgsea size filtering for ", nm,
         ". This usually means the ranked gene identifiers do not match msigdbr gene symbols, or the wrong DE file was selected. Diagnostic saved to: ",
         diag_file, call. = FALSE)
  }

  set.seed(1)
  res <- fgsea::fgsea(
    pathways = pathways,
    stats = stats_vec,
    minSize = fgsea_minSize,
    maxSize = fgsea_maxSize,
    eps = fgsea_eps,
    nproc = fgsea_nproc
  )

  if (nrow(as.data.frame(res)) == 0) {
    diag_file <- file.path(out_dir, paste0("stepH2w9_current78_fgsea_returned_zero_rows_", nm, ".csv"))
    diag_df <- data.frame(
      pathway = names(pathways),
      n_genes_in_pathway = vapply(pathways, length, integer(1)),
      n_genes_present_in_rank = pathway_overlap_n,
      passes_size_filter = pathway_overlap_n >= fgsea_minSize & pathway_overlap_n <= fgsea_maxSize,
      stringsAsFactors = FALSE
    )
    write_csv(diag_df, diag_file)
    stop("fgsea returned zero rows for ", nm,
         " despite pathway overlap checks. Diagnostic saved to: ", diag_file, call. = FALSE)
  }

  fgsea_results[[nm]] <- clean_fgsea_out(res, contrast_label, branch)
}

