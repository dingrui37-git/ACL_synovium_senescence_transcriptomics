infer_group <- function(x) {
  if (grepl("^CON", x)) return("Control")
  if (grepl("^INJS", x)) return("ACLT_1W")
  if (grepl("^INJL", x)) return("ACLT_4W")
  return(NA_character_)
}
infer_time <- function(x) {
  if (grepl("^CON", x)) return("t0")
  if (grepl("^INJS", x)) return("t7")
  if (grepl("^INJL", x)) return("t28")
  return(NA_character_)
}
infer_number <- function(x) as.integer(sub("^[A-Z]+", "", x))

sample_metadata <- data.frame(
  sample_id = sample_cols,
  group = vapply(sample_cols, infer_group, character(1)),
  time_point = vapply(sample_cols, infer_time, character(1)),
  sample_number = vapply(sample_cols, infer_number, integer(1)),
  count_column = sample_cols,
  stringsAsFactors = FALSE
)
sample_metadata$group <- factor(sample_metadata$group, levels = c("Control", "ACLT_1W", "ACLT_4W"))
sample_metadata$time_point <- factor(sample_metadata$time_point, levels = c("t0", "t7", "t28"))

if (anyNA(sample_metadata$group)) stop("Failed to infer group for one or more samples.")
if (any(table(sample_metadata$group) != 6)) {
  cat("WARNING: expected 6 samples per group, but observed:\n")
  print(table(sample_metadata$group))
}

