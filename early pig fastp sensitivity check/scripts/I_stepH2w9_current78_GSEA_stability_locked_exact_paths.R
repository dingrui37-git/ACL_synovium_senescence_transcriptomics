stop_if_missing <- function(file, label) {
  if (!file.exists(file)) stop("Missing ", label, ": ", file, call. = FALSE)
}

safe_read_csv <- function(file) {
  read.csv(file, stringsAsFactors = FALSE, check.names = FALSE, fileEncoding = "UTF-8-BOM")
}

write_csv <- function(x, file) {
  write.csv(x, file, row.names = FALSE, fileEncoding = "UTF-8")
  cat("Saved: ", file, "\n", sep = "")
}

clean_symbol <- function(x) {
  x <- as.character(x)
  x <- trimws(x)
  x[x %in% c("", "NA", "NaN", "NULL", "null", "None", "none")] <- NA_character_
  x
}

find_col <- function(df, candidates, required = TRUE, label = "column") {
  hit <- candidates[candidates %in% colnames(df)]
  if (length(hit) > 0) return(hit[1])
  if (required) {
    stop("Could not find ", label, ". Checked: ", paste(candidates, collapse = ", "),
         "\nAvailable columns: ", paste(colnames(df), collapse = ", "), call. = FALSE)
  }
  NA_character_
}

safe_p <- function(p) {
  p <- suppressWarnings(as.numeric(p))
  p[is.na(p)] <- NA_real_
  p[p <= 0] <- .Machine$double.xmin
  p
}

build_symbol_map_from_de_files <- function(files) {
  map_list <- list()
  for (f in files) {
    if (!file.exists(f)) next
    df <- safe_read_csv(f)
    gene_id_col <- find_col(df, c("gene_id", "pig_ensg", "GeneID", "Geneid", "feature_id", "ensembl_gene_id"), FALSE, "gene id column for symbol map")
    symbol_col <- find_col(df, c("gene_name", "gene_symbol", "SYMBOL", "symbol", "pig_symbol", "external_gene_name"), FALSE, "symbol column for symbol map")
    if (is.na(gene_id_col) || is.na(symbol_col)) next
    tmp <- data.frame(
      gene_id = clean_symbol(df[[gene_id_col]]),
      gene_symbol = clean_symbol(df[[symbol_col]]),
      stringsAsFactors = FALSE
    )
    tmp <- tmp[!is.na(tmp$gene_id) & tmp$gene_id != "" & !is.na(tmp$gene_symbol) & tmp$gene_symbol != "", , drop = FALSE]
    tmp <- tmp[!duplicated(tmp$gene_id), , drop = FALSE]
    map_list[[length(map_list) + 1]] <- tmp
  }
  if (length(map_list) == 0) {
    return(data.frame(gene_id = character(0), gene_symbol = character(0), stringsAsFactors = FALSE))
  }
  out <- do.call(rbind, map_list)
  out <- out[!duplicated(out$gene_id), , drop = FALSE]
  rownames(out) <- NULL
  out
}


score_de_candidate <- function(file, contrast_tag) {
  bn <- tolower(basename(file))
  cols <- tryCatch(tolower(names(read.csv(file, nrows = 1, check.names = FALSE))), error = function(e) character(0))
  score <- 0
  if (grepl("qlf|edger|de", bn)) score <- score + 20
  if (grepl("trimmed|h2w6", bn)) score <- score + 10
  if (grepl(contrast_tag, bn)) score <- score + 30
  if (any(cols %in% c("logfc", "log2fc", "log2foldchange"))) score <- score + 20
  if (any(cols %in% c("pvalue", "p.value", "pval", "p.value.qlf", "p"))) score <- score + 20
  if (any(cols %in% c("gene_name", "gene_symbol", "symbol", "pig_symbol", "external_gene_name"))) score <- score + 10
  if (grepl("summary|stability|fgsea|gsea|ranked|count|matrix|manifest|sample|assignment|qc|status|overall|parameter|method", bn)) score <- score - 100
  score
}

find_trimmed_de_file <- function(contrast_tag) {
  # First try likely exact names. If not found, fall back to a scored recursive search.
  exact_candidates <- c(
    file.path(fastp_tables_dir, paste0("stepH2w6_trimmed_edgeR_QLF_DE_", contrast_tag, "_vs_CON.csv")),
    file.path(fastp_tables_dir, paste0("stepH2w6_trimmed_edgeR_QLF_", contrast_tag, "_vs_CON.csv")),
    file.path(fastp_tables_dir, paste0("stepH2w6_trimmed_DE_", contrast_tag, "_vs_CON_QLF.csv")),
    file.path(fastp_tables_dir, paste0("stepH2w6_trimmed_edgeR_QLF_DE_", contrast_tag, "_vs_Control.csv")),
    file.path(fastp_tables_dir, paste0("stepH2w6_trimmed_DE_", contrast_tag, "_vs_Control_QLF.csv"))
  )
  hit <- exact_candidates[file.exists(exact_candidates)]
  if (length(hit) > 0) return(normalizePath(hit[1], winslash = "/", mustWork = FALSE))

  files <- list.files(fastp_tables_dir, pattern = "\\.csv$", recursive = TRUE, full.names = TRUE)
  if (length(files) == 0) return(NA_character_)
  scores <- vapply(files, score_de_candidate, numeric(1), contrast_tag = contrast_tag)
  cand <- data.frame(file = normalizePath(files, winslash = "/", mustWork = FALSE),
                     basename = basename(files),
                     score = scores,
                     stringsAsFactors = FALSE)
  cand <- cand[order(-cand$score, cand$basename), , drop = FALSE]
  cand_file <- file.path(out_dir, paste0("stepH2w9_current78_trimmed_DE_candidates_", contrast_tag, ".csv"))
  write_csv(cand, cand_file)
  if (nrow(cand) == 0 || cand$score[1] < 60) {
    stop("Could not identify trimmed DE table for ", contrast_tag,
         ". Candidate list saved to: ", cand_file, call. = FALSE)
  }
  cand$file[1]
}

rank_one_table <- function(de_file, contrast_label, branch_label, symbol_map = NULL, hallmark_symbols = NULL) {
  df <- safe_read_csv(de_file)

  gene_id_col <- find_col(df, c("gene_id", "pig_ensg", "GeneID", "Geneid", "feature_id", "ensembl_gene_id"), TRUE, "gene id column")
  symbol_col <- find_col(df, c("gene_name", "gene_symbol", "SYMBOL", "symbol", "pig_symbol", "external_gene_name"), FALSE, "gene symbol column")
  logfc_col <- find_col(df, c("logFC", "LogFC", "log2FC", "log2FoldChange", "log2_fold_change"), TRUE, "logFC column")
  p_col <- find_col(df, c("PValue", "P.Value", "pvalue", "P.value", "PVAL", "P", "p"), TRUE, "P value column")
  fdr_col <- find_col(df, c("FDR", "adj.P.Val", "padj", "qvalue"), FALSE, "FDR column")

  gene_id <- clean_symbol(df[[gene_id_col]])

  # Current formal GSEA uses pig gene symbols. Some trimmed DE files contain only Ensembl IDs.
  # If symbol column is absent or does not overlap with Hallmark symbols, map Ensembl IDs to symbols
  # using the untrimmed DE annotation table.
  gene_symbol_from_file <- if (!is.na(symbol_col)) clean_symbol(df[[symbol_col]]) else rep(NA_character_, nrow(df))
  n_symbol_overlap_from_file <- if (!is.null(hallmark_symbols)) {
    length(intersect(unique(gene_symbol_from_file[!is.na(gene_symbol_from_file)]), hallmark_symbols))
  } else {
    NA_integer_
  }

  gene_symbol <- gene_symbol_from_file
  symbol_source <- if (!is.na(symbol_col)) paste0("file_column:", symbol_col) else "none"

  need_symbol_map <- is.na(symbol_col) ||
    all(is.na(gene_symbol_from_file)) ||
    (!is.null(hallmark_symbols) && !is.na(n_symbol_overlap_from_file) && n_symbol_overlap_from_file < 100)

  if (need_symbol_map && !is.null(symbol_map) && nrow(symbol_map) > 0) {
    mapped <- symbol_map$gene_symbol[match(gene_id, symbol_map$gene_id)]
    use_mapped <- !is.na(mapped) & mapped != ""
    gene_symbol[use_mapped] <- mapped[use_mapped]
    symbol_source <- paste0("mapped_from_gene_id_using_untrimmed_DE_annotation; original_symbol_overlap=", n_symbol_overlap_from_file)
  }

  # Do not fall back to Ensembl IDs for formal Hallmark GSEA, because msigdbr Hallmark is gene-symbol based here.
  logfc <- suppressWarnings(as.numeric(df[[logfc_col]]))
  pval <- safe_p(df[[p_col]])
  fdr <- if (!is.na(fdr_col)) suppressWarnings(as.numeric(df[[fdr_col]])) else rep(NA_real_, nrow(df))
  rank_stat <- sign(logfc) * (-log10(pval))

  rank_df <- data.frame(
    contrast = contrast_label,
    branch = branch_label,
    gene_id = gene_id,
    gene_symbol = gene_symbol,
    logFC = logfc,
    PValue = pval,
    FDR = fdr,
    rank_stat = rank_stat,
    stringsAsFactors = FALSE
  )

  keep <- !is.na(rank_df$gene_symbol) & rank_df$gene_symbol != "" &
    !is.na(rank_df$logFC) & !is.na(rank_df$PValue) & rank_df$PValue > 0 &
    !is.na(rank_df$rank_stat) & is.finite(rank_df$rank_stat)
  removed_invalid_rows <- sum(!keep)
  rank_df <- rank_df[keep, , drop = FALSE]

  if (!is.null(hallmark_symbols)) {
    n_symbol_overlap_final <- length(intersect(unique(rank_df$gene_symbol), hallmark_symbols))
  } else {
    n_symbol_overlap_final <- NA_integer_
  }

  ord <- order(-abs(rank_df$rank_stat), rank_df$gene_symbol)
  rank_df <- rank_df[ord, , drop = FALSE]
  duplicated_symbol_rows_removed <- sum(duplicated(rank_df$gene_symbol))
  rank_df <- rank_df[!duplicated(rank_df$gene_symbol), , drop = FALSE]
  rank_df <- rank_df[order(rank_df$rank_stat, decreasing = TRUE), , drop = FALSE]
  rownames(rank_df) <- NULL

  stats_vec <- rank_df$rank_stat
  names(stats_vec) <- rank_df$gene_symbol
  stats_vec <- sort(stats_vec, decreasing = TRUE)

  list(
    rank_df = rank_df,
    stats_vec = stats_vec,
    n_ranked_symbols = length(stats_vec),
    removed_invalid_rows = removed_invalid_rows,
    duplicated_symbol_rows_removed = duplicated_symbol_rows_removed,
    gene_id_col = gene_id_col,
    symbol_col = symbol_col,
    symbol_source = symbol_source,
    n_symbol_overlap_from_file = n_symbol_overlap_from_file,
    n_symbol_overlap_final = n_symbol_overlap_final,
    logfc_col = logfc_col,
    p_col = p_col,
    fdr_col = fdr_col
  )
}

clean_fgsea_out <- function(fgsea_result, contrast_label, branch_label) {
  out <- as.data.frame(fgsea_result, stringsAsFactors = FALSE)

  # If fgsea returns zero pathways, do not trigger "$<- data.frame" replacement errors.
  # Instead, return a well-formed empty result and let the caller stop with a clear diagnostic.
  if (nrow(out) == 0) {
    out <- data.frame(
      branch = character(0),
      contrast = character(0),
      pathway = character(0),
      pval = numeric(0),
      padj = numeric(0),
      log2err = numeric(0),
      ES = numeric(0),
      NES = numeric(0),
      size = integer(0),
      leadingEdge_size = integer(0),
      leadingEdge_genes = character(0),
      stringsAsFactors = FALSE
    )
    return(out)
  }

  if ("leadingEdge" %in% colnames(out)) {
    out$leadingEdge_size <- vapply(out$leadingEdge, length, integer(1))
    out$leadingEdge_genes <- vapply(out$leadingEdge, function(x) paste(x, collapse = ";"), character(1))
    out$leadingEdge <- NULL
  }
  out$contrast <- rep(contrast_label, nrow(out))
  out$branch <- rep(branch_label, nrow(out))
  out <- out[, c("branch", "contrast", setdiff(colnames(out), c("branch", "contrast"))), drop = FALSE]
  out
}

stability_label <- function(spearman_nes, max_abs_delta_target, target_direction_agreement) {
  if (is.na(spearman_nes)) return("needs_review")
  if (spearman_nes >= 0.98 && max_abs_delta_target <= 0.10 && isTRUE(target_direction_agreement)) return("highly_stable")
  if (spearman_nes >= 0.95 && max_abs_delta_target <= 0.20 && isTRUE(target_direction_agreement)) return("stable")
  if (spearman_nes >= 0.90 && max_abs_delta_target <= 0.35) return("mostly_stable")
  "needs_review"
}

