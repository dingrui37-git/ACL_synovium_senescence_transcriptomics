          file.path(subdirs["source_data"], "StepPCA_MDS_02_sample_metadata_inferred.csv"),
          row.names = FALSE)

# edgeR filtering and TMM normalization, consistent with the DE-analysis preprocessing logic.
dge <- DGEList(counts = count_mat, group = sample_metadata$group)
keep <- filterByExpr(dge, group = sample_metadata$group)
dge_filtered <- dge[keep, , keep.lib.sizes = FALSE]
dge_filtered <- calcNormFactors(dge_filtered, method = "TMM")

logcpm <- cpm(dge_filtered, log = TRUE, prior.count = 1, normalized.lib.sizes = TRUE)

filter_summary <- data.frame(
